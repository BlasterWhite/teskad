//! What a Codex agent generates (hangar-core's agent/images.rs, its
//! `image:generated` event): each image attached to the card of the turn
//! that made it, where its agent speaks (its workspace's channel, or its
//! thread), the prompt it was made from as its description when that is
//! short; in a message of its own under the agent's name when no card
//! stands for it (the turn over, its card full, or not edited); past
//! [`IMAGE_LIMIT`], or refused by Discord as too large, a line that says
//! where it stays. A pane the bot does not follow (a headless child, a
//! pane neither a channel's voice nor a worker with a thread) gives
//! nothing.
//!
//! The file is Codex's: read where it is, never moved nor deleted.

use std::path::{Path, PathBuf};

use crate::bot::Bot;
use crate::cards::{self, Image};
use crate::rest::Upload;
use crate::shares::too_large;

/// The largest image attached: 8 MiB, what Discord took from anyone until
/// 2025, under what a server with no boost takes since
/// ([`crate::shares::UPLOAD_LIMIT`]). One larger is said by a line.
pub const IMAGE_LIMIT: u64 = 8 * 1024 * 1024;

/// What was found at an image's path.
#[derive(Debug, PartialEq, Eq)]
enum Found {
    /// Its bytes.
    Bytes(Vec<u8>),
    /// Past [`IMAGE_LIMIT`]: its size alone.
    TooLarge(u64),
}

/// The image at `path`, read where it is; past [`IMAGE_LIMIT`], its size
/// alone, the file not read.
fn read_image(path: &Path) -> std::io::Result<Found> {
    let size = std::fs::metadata(path)?.len();
    if size > IMAGE_LIMIT {
        return Ok(Found::TooLarge(size));
    }
    let bytes = std::fs::read(path)?;
    // Grown since it was looked at.
    let read = bytes.len() as u64;
    if read > IMAGE_LIMIT {
        return Ok(Found::TooLarge(read));
    }
    Ok(Found::Bytes(bytes))
}

/// The file's name, as said and uploaded.
fn file_name(path: &Path) -> String {
    path.file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .filter(|name| !name.is_empty())
        .unwrap_or_else(|| "image.png".into())
}

/// The prompt as an image's description, when it is short enough for one
/// (what Discord takes): a longer one is not cut, the image goes without.
fn description_of(prompt: Option<&str>) -> Option<String> {
    prompt
        .map(str::trim)
        .filter(|prompt| !prompt.is_empty() && prompt.chars().count() <= cards::DESCRIPTION_MAX)
        .map(str::to_string)
}

/// `file`'s name in the upload, apart from those of the images on the card
/// already: two named alike would show one of them twice.
fn attachment_for(file: &str, on_card: &[Image]) -> String {
    let base = cards::attachment_name(file);
    let mut name = base.clone();
    let mut n = 1;
    while on_card.iter().any(|image| image.attachment == name) {
        n += 1;
        name = format!("{n}_{base}");
    }
    name
}

impl Bot {
    /// Image `path`, generated by pane `pane`'s agent from `prompt`. In the
    /// pane's lane: after the start of the turn that made it, before its
    /// end.
    pub(crate) async fn on_image(&self, pane: &str, path: PathBuf, prompt: Option<String>) {
        let Some((ws, thread, name)) = self.shown_in(pane) else {
            return;
        };
        let words = self.words();
        let file = file_name(&path);
        let found = {
            let path = path.clone();
            match tokio::task::spawn_blocking(move || read_image(&path)).await {
                Ok(read) => read,
                Err(stopped) => Err(std::io::Error::other(stopped)),
            }
        };
        let turn = self.state().turns.get(pane).cloned();
        // Where its turn's card is, else where its agent speaks.
        let (ws, thread) = match &turn {
            Some(turn) => (turn.ws.clone(), turn.thread.clone()),
            None => (ws, thread),
        };
        let away =
            |size: u64| cards::generated_away(words, &name, &file, size, &path.to_string_lossy());
        let bytes = match found {
            Ok(Found::Bytes(bytes)) => bytes,
            Ok(Found::TooLarge(size)) => {
                self.say_image(&ws, &name, thread.as_deref(), away(size))
                    .await;
                return;
            }
            Err(error) => {
                eprintln!("discord: an image of {name} cannot be read: {error}");
                return;
            }
        };
        let size = bytes.len() as u64;
        let description = description_of(prompt.as_deref());
        // On the card of the turn under way, while it has room.
        if let Some(turn) = turn.filter(|turn| turn.images.len() < cards::GALLERY_MAX) {
            let mut images = turn.images;
            let attachment = attachment_for(&file, &images);
            let upload = Upload {
                name: attachment.clone(),
                bytes: bytes.clone(),
            };
            images.push(Image {
                attachment,
                description: description.clone(),
            });
            let card = cards::with_images(
                cards::turn(words, &name, turn.started, &turn.calls, pane),
                &images,
            );
            let edited = self
                .edit_as_with(
                    &turn.ws,
                    turn.thread.as_deref(),
                    &turn.message,
                    card,
                    vec![upload],
                )
                .await;
            match edited {
                Ok(()) => {
                    if let Some(turn) = self.state().turns.get_mut(pane) {
                        turn.images = images;
                    }
                    return;
                }
                Err(error) if too_large(&error) => {
                    self.say_image(&ws, &name, thread.as_deref(), away(size))
                        .await;
                    return;
                }
                // The card not edited (deleted on Discord, say): the image
                // in a message of its own.
                Err(error) => eprintln!("discord: an image on the turn card of {name}: {error}"),
            }
        }
        let image = Image {
            attachment: attachment_for(&file, &[]),
            description,
        };
        let upload = Upload {
            name: image.attachment.clone(),
            bytes,
        };
        let card = cards::generated(words, &name, &image);
        match self
            .post_as(&ws, &name, thread.as_deref(), card, vec![upload])
            .await
        {
            Ok(_) => {}
            Err(error) if too_large(&error) => {
                self.say_image(&ws, &name, thread.as_deref(), away(size))
                    .await;
            }
            Err(error) => eprintln!("discord: an image of {name}: {error}"),
        }
    }

    /// What is said of an image not attached, under its agent's name.
    async fn say_image(&self, ws: &str, name: &str, thread: Option<&str>, line: serde_json::Value) {
        if let Err(error) = self.post_as(ws, name, thread, line, Vec::new()).await {
            eprintln!("discord: an image of {name}: {error}");
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_image_is_read_where_it_is_and_one_too_large_is_not_read() {
        let dir = tempfile::tempdir().unwrap();
        let small = dir.path().join("ig_1.png");
        std::fs::write(&small, b"\x89PNG").unwrap();
        assert_eq!(
            read_image(&small).unwrap(),
            Found::Bytes(b"\x89PNG".to_vec())
        );
        // Codex's file stays where it is.
        assert!(small.exists());
        let large = dir.path().join("ig_2.png");
        std::fs::File::create(&large)
            .unwrap()
            .set_len(IMAGE_LIMIT + 1)
            .unwrap();
        assert_eq!(
            read_image(&large).unwrap(),
            Found::TooLarge(IMAGE_LIMIT + 1)
        );
        assert!(read_image(&dir.path().join("gone.png")).is_err());
    }

    #[test]
    fn the_prompt_describes_an_image_when_it_is_short() {
        assert_eq!(
            description_of(Some("  Un chat roux sur un toit ")).as_deref(),
            Some("Un chat roux sur un toit")
        );
        assert_eq!(description_of(Some("   ")), None);
        assert_eq!(description_of(None), None);
        let long = "a".repeat(cards::DESCRIPTION_MAX + 1);
        assert_eq!(description_of(Some(long.as_str())), None);
        let longest = "é".repeat(cards::DESCRIPTION_MAX);
        assert_eq!(description_of(Some(longest.as_str())), Some(longest));
    }

    #[test]
    fn two_images_of_a_card_never_share_a_name() {
        let on = |names: &[&str]| -> Vec<Image> {
            names
                .iter()
                .map(|name| Image {
                    attachment: (*name).into(),
                    description: None,
                })
                .collect()
        };
        assert_eq!(attachment_for("ig_1.png", &[]), "ig_1.png");
        assert_eq!(attachment_for("ig 1.png", &[]), "ig_1.png");
        assert_eq!(attachment_for("ig_1.png", &on(&["ig_1.png"])), "2_ig_1.png");
        assert_eq!(
            attachment_for("ig_1.png", &on(&["ig_1.png", "2_ig_1.png"])),
            "3_ig_1.png"
        );
        assert_eq!(file_name(Path::new("/codex/images/ig_1.png")), "ig_1.png");
        assert_eq!(file_name(Path::new("/")), "image.png");
    }
}
